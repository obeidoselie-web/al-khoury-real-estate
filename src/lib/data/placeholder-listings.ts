const IMAGE_WIDTH = 1600;
const IMAGE_HEIGHT = 1067;
const VARIANTS = 4;

const SCENE_NAMES: Record<PropertyType, string> = {
  house: 'house exterior',
  apartment: 'apartment building',
  commercial: 'commercial building',
  land: 'landscape',
};

/** Three placeholder photos for a listing, rotated so neighbouring cards don't look identical. */
function photos(type: PropertyType, start: number, title: string): ListingImage[] {
  return [0, 1, 2].map((offset) => {
    const variant = ((start + offset - 1) % VARIANTS) + 1;
    return {
      src: `/images/placeholders/${type}-${variant}.jpg`,
      alt: `${title} — illustrated ${SCENE_NAMES[type]} (placeholder photo ${offset + 1} of 3)`,
      width: IMAGE_WIDTH,
      height: IMAGE_HEIGHT,
    };
  });
}

